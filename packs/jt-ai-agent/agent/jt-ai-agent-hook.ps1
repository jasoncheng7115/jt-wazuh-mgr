# jt-ai-agent-hook.ps1 - BETA - Windows audit hook for AI coding agents, for Wazuh
# Part of the jt-ai-agent rule pack (jt-wazuh-mgr).  AGPL-3.0-or-later, Jason Tools Co., Ltd.
#
# BETA (jt-ai-agent 1.6): the Windows counterpart of jt-ai-agent-hook.py for Claude Code, Codex,
# Gemini CLI, Cursor and GitHub Copilot. It writes the same JSON lines, marked "platform":"windows"
# and "hook":"ps1-beta", so the same rules apply. Not yet covered on Windows: opencode, the SSH
# destinations of a command (jt_ai.remote), browser automation detail, Codex patch summaries,
# the Gemini "hook turned off" check, sudo/login users and git project names.
#
# Installed as C:\Program Files\jt-ai-agent\jt-ai-agent-hook.ps1 (administrators only can change it)
# and run by Windows PowerShell 5.1, which every Windows has:
#   powershell.exe -NoProfile -NonInteractive -ExecutionPolicy Bypass -File "C:\Program Files\jt-ai-agent\jt-ai-agent-hook.ps1" -Agent claude-code
# The same command line works when the agent runs hooks through Git Bash, cmd or PowerShell.
#
#   -Agent claude-code|codex|gemini|cursor|copilot   which agent called (default claude-code)
#   -Event NAME      Copilot only: the event name its configuration passes
#   -SyncConfig      SYSTEM, from the scheduled task: copy the setting the Wazuh manager delivers to
#                    C:\ProgramData\jt-ai-agent\config, where every user's hook can read it
#
# It writes one line per tool call to C:\ProgramData\jt-ai-agent\actions.log, which users may only
# append to (they cannot read or rewrite it), and prompts (only when the server turns them on)
# to prompts.log next to it. Secrets in command lines and prompts are replaced with *** first, with
# the Python hook's patterns. It never blocks or changes anything: it always exits 0, prints nothing,
# and prints {} for Gemini CLI, Cursor and Copilot, which read the answer as JSON.
#
# JT_AI_AGENT_LOG, JT_AI_AGENT_PROMPT_LOG and JT_AI_AGENT_CONFIG override the paths (tests).

