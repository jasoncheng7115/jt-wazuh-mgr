function Get-Field($obj, [string]$name) {
    if ($null -eq $obj) { return $null }
    if ($obj -is [System.Collections.IDictionary]) { return $obj[$name] }
    $p = $obj.PSObject.Properties[$name]
    if ($p) { return $p.Value }
    return $null
}

function As-Object($value) {
    # tool input may arrive as an object or as a JSON string (Copilot's toolArgs)
    if ($value -is [string]) {
        try { return ($value | ConvertFrom-Json) } catch { return $null }
    }
    return $value
}

function Protect-Text([string]$text) {
    foreach ($r in $Redact) { $text = [regex]::Replace($text, $r[0], $r[1]) }
    return $text
}

function Short($text, [int]$limit = $MaxShort) {
    $t = Protect-Text ([string]$text)
    if ($t.Length -le $limit) { return $t }
    return $t.Substring(0, $limit) + '...'
}

function Get-Stamp {
    $now = Get-Date
    $off = [TimeZoneInfo]::Local.GetUtcOffset($now)
    $sign = if ($off.Ticks -lt 0) { '-' } else { '+' }
    return $now.ToString('yyyy-MM-ddTHH:mm:ss') + $sign + ('{0:00}{1:00}' -f [Math]::Abs($off.Hours), [Math]::Abs($off.Minutes))
}

function Add-Line([string]$path, [string]$line) {
    $bytes = [Text.Encoding]::UTF8.GetBytes($line + "`n")
    try {
        # Windows PowerShell (.NET Framework): ask for append rights only, which is all users have
        $fs = New-Object IO.FileStream($path, [IO.FileMode]::Append, [Security.AccessControl.FileSystemRights]::AppendData,
                                       [IO.FileShare]::ReadWrite, 4096, [IO.FileOptions]::None)
    } catch {
        if (-not (Test-Path -LiteralPath $path)) { return $false }
        $fs = New-Object IO.FileStream($path, [IO.FileMode]::Append, [IO.FileAccess]::Write, [IO.FileShare]::ReadWrite)
    }
    try { $fs.Write($bytes, 0, $bytes.Length) } finally { $fs.Close() }
    return $true
}

function ConvertTo-Line($obj) {
    return ($obj | ConvertTo-Json -Compress -Depth 6)
}

function Read-Config([string]$text) {
    $conf = @{}
    foreach ($line in ($text -split "`r?`n")) {
        $line = ($line -split '#', 2)[0].Trim()
        if ($line -notmatch '=') { continue }
        $kv = $line -split '=', 2
        $k = $kv[0].Trim().ToLower(); $v = $kv[1].Trim().ToLower()
        if ($k -eq 'prompts' -and $PromptModes -contains $v -and -not $conf.ContainsKey('prompts')) { $conf['prompts'] = $v }
    }
    return $conf
}

function Get-PromptMode {
    $paths = if ($env:JT_AI_AGENT_CONFIG) { @($ConfigLocal) } else { $ConfigShared + @($ConfigLocal) }
    foreach ($p in $paths) {
        try {
            $c = Read-Config ([IO.File]::ReadAllText($p))
            if ($c.ContainsKey('prompts')) { return $c['prompts'] }
            return 'off'
        } catch { continue }
    }
    return 'off'
}

function Sync-Config {
    $source = $null
    foreach ($p in $ConfigShared) {
        try { $source = Read-Config ([IO.File]::ReadAllText($p)); break } catch { continue }
    }
    if ($null -eq $source) { return }
    $new = if ($source.ContainsKey('prompts')) { $source['prompts'] } else { 'off' }
    $old = 'none'
    if (Test-Path -LiteralPath $ConfigLocal) {
        $c = Read-Config ([IO.File]::ReadAllText($ConfigLocal))
        $old = if ($c.ContainsKey('prompts')) { $c['prompts'] } else { 'off' }
        if ($old -eq $new) { return }
    }
    $dir = Split-Path -Parent $ConfigLocal
    if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
    $body = "# jt-ai-agent settings, copied from the Wazuh manager by jt-ai-agent-hook.ps1 -SyncConfig.`r`n" +
            "# Change them on the manager (agent group ai-agent, file jt-ai-agent.conf), not here.`r`nprompts = $new`r`n"
    [IO.File]::WriteAllText($ConfigLocal, $body)
    $rec = [ordered]@{ v = 1; ts = (Get-Stamp); host = [Environment]::MachineName; user = 'SYSTEM'; event = 'AuditConfig';
                       agent = 'jt-ai-agent'; platform = 'windows'; hook = 'ps1-beta'; prompts = $new; previous = $old }
    Add-Line $Log (ConvertTo-Line @{ jt_ai = $rec }) | Out-Null
}

function Normalize-Event($e, [string]$agent, [string]$eventName) {
    # every agent's payload in Claude Code's shape: hook_event_name, session_id, cwd, tool_name, tool_input...
    $out = @{}
    foreach ($k in @('session_id', 'cwd', 'source', 'reason', 'prompt', 'permission_mode', 'tool_use_id', 'model',
                     'agent_type', 'tool_response', 'error')) {
        $v = Get-Field $e $k
        if ($null -ne $v) { $out[$k] = $v }
    }
    $name = [string](Get-Field $e 'hook_event_name')
    if ($agent -eq 'gemini') {
        if (-not $GeminiEvents.ContainsKey($name)) { return $null }
        $out['hook_event_name'] = $GeminiEvents[$name]
        $tool = Get-Field $e 'tool_name'
        $mcp = Get-Field $e 'mcp_context'
        if ($tool) {
            $server = Get-Field $mcp 'server_name'
            if ($server) { $out['tool_raw'] = $tool; $tool = "mcp__${server}__$tool" }
            $out['tool_name'] = $tool
        }
        $out['tool_input'] = As-Object (Get-Field $e 'tool_input')
    } elseif ($agent -eq 'cursor') {
        if (-not $CursorEvents.ContainsKey($name)) { return $null }
        $out['hook_event_name'] = $CursorEvents[$name]
        $out['session_id'] = Get-Field $e 'conversation_id'
        $out['account'] = Get-Field $e 'user_email'
        $out['permission_mode'] = Get-Field $e 'composer_mode'
        if (-not $out['cwd']) { $roots = Get-Field $e 'workspace_roots'; if ($roots) { $out['cwd'] = @($roots)[0] } }
        $tool = [string](Get-Field $e 'tool_name')
        if ($tool) {
            $srv = Get-Field $e 'mcp_server_name'
            if ($tool.StartsWith('MCP:') -or $srv) {
                $out['tool_raw'] = $tool
                $bare = if ($tool.StartsWith('MCP:')) { $tool.Substring(4) } else { $tool }
                $tool = "mcp__$(if ($srv) { $srv } else { 'unknown' })__$bare"
            }
            $out['tool_name'] = $tool
        }
        $out['tool_input'] = As-Object (Get-Field $e 'tool_input')
        if ($name -eq 'postToolUseFailure') {
            $out['failed'] = $true
            $out['error'] = (@((Get-Field $e 'failure_type'), (Get-Field $e 'error_message')) | Where-Object { $_ }) -join ': '
        }
    } elseif ($agent -eq 'copilot') {
        if (-not $eventName) { $eventName = $name }
        if (-not $CopilotEvents.ContainsKey($eventName)) { return $null }
        $out['hook_event_name'] = $CopilotEvents[$eventName]
        $sid = Get-Field $e 'sessionId'; if ($sid) { $out['session_id'] = $sid }
        $an = Get-Field $e 'agentName'; if ($an) { $out['agent_type'] = $an }
        $tool = Get-Field $e 'toolName'
        if ($tool) { $out['tool_name'] = $tool }
        $ti = As-Object (Get-Field $e 'toolArgs'); if (-not $ti) { $ti = As-Object (Get-Field $e 'toolInput') }
        $out['tool_input'] = $ti
        $res = Get-Field $e 'toolResult'
        if ($res) { $out['tool_response'] = @{ error = ((Get-Field $res 'resultType') -notin @($null, 'success')) } }
    } else {
        $out['hook_event_name'] = $name
        $tool = Get-Field $e 'tool_name'
        if ($tool) { $out['tool_name'] = $tool }
        $out['tool_input'] = Get-Field $e 'tool_input'
    }
    return $out
}

function Test-Failed($resp) {
    if ($null -eq $resp) { return $false }
    foreach ($k in @('error', 'is_error', 'isError')) {
        $v = Get-Field $resp $k
        if ($v -and $v -ne $false) { return $true }
    }
    return $false
}

function New-Record($ev, [string]$agent) {
    $rec = [ordered]@{ v = 1; ts = (Get-Stamp); host = [Environment]::MachineName; user = [Environment]::UserName }
    $map = [ordered]@{ hook_event_name = 'event'; session_id = 'session'; cwd = 'cwd'; permission_mode = 'mode';
                       agent_type = 'subagent'; tool_name = 'tool'; tool_use_id = 'call'; source = 'source';
                       model = 'model'; reason = 'reason'; account = 'account'; tool_raw = 'tool_raw' }
    foreach ($k in $map.Keys) {
        $v = $ev[$k]
        if ($v -is [string] -and $v) { $rec[$map[$k]] = $v.Substring(0, [Math]::Min($v.Length, $MaxShort)) }
    }
    $rec['agent'] = $agent
    $rec['platform'] = 'windows'
    $rec['hook'] = 'ps1-beta'
    if ($ev['failed']) { $rec['failed'] = $true }
    if ($ev['error'] -is [string] -and $ev['error']) { $rec['error'] = Short (($ev['error'] -split "`n")[0]) 200 }
    $tool = [string]$rec['tool']
    if ($tool -and $ToolMaps.ContainsKey($agent)) {
        $canon = $ToolMaps[$agent][$tool]
        if (-not $canon -and $agent -eq 'copilot') { $canon = $ToolMaps[$agent][$tool.ToLower()] }
        if ($canon -and $canon -ne $tool) { $rec['tool_raw'] = $tool; $rec['tool'] = $canon; $tool = $canon }
    }
    if ($tool.StartsWith('mcp__')) {
        $parts = $tool -split '__'
        if ($parts.Count -ge 3) { $rec['mcp_server'] = $parts[1]; $rec['mcp_tool'] = ($parts[2..($parts.Count - 1)] -join '__') }
    }
    $ti = $ev['tool_input']
    if ($null -eq $ti) { return $rec }
    if ($tool -eq 'Bash') {
        $cmd = Get-Field $ti 'command'
        if ($cmd -is [array]) { $cmd = ($cmd -join ' ') }
        if ($cmd) {
            $cmd = [string]$cmd
            $clean = Protect-Text $cmd
            $rec['cmd'] = if ($clean.Length -le $MaxCmd) { $clean } else { $clean.Substring(0, $MaxCmd) + '...' }
            $rec['cmd_len'] = $cmd.Length
            if ($clean -ne $cmd) { $rec['redacted'] = $true }
        }
        return $rec
    }
    if ($tool -eq 'Task' -or $tool -eq 'Agent') {
        foreach ($k in @('description', 'subagent_type')) {
            $v = Get-Field $ti $k
            if ($v) { $rec["task_$k"] = Short $v }
        }
        return $rec
    }
    foreach ($k in @('file_path', 'filePath', 'notebook_path', 'path', 'target_file', 'dir_path')) {
        $v = Get-Field $ti $k
        if ($v) { $rec['path'] = (Short $v 1000).Replace('\', '/'); break }    # forward slashes: the rules match both platforms
    }
    foreach ($k in @('content', 'file_text', 'contents')) {
        $v = Get-Field $ti $k
        if ($v -is [string]) { $rec['size'] = $v.Length; break }
    }
    foreach ($k in @('pattern', 'glob', 'query', 'url')) {
        $v = Get-Field $ti $k
        if ($v) { $rec[$k] = Short $v $(if ($k -eq 'url') { 1000 } else { $MaxShort }) }
    }
    if (-not ($rec.Contains('path') -or $rec.Contains('pattern') -or $rec.Contains('glob') -or $rec.Contains('query') -or $rec.Contains('url'))) {
        $names = @($ti.PSObject.Properties | ForEach-Object { $_.Name } | Sort-Object | Select-Object -First 20)
        if ($names.Count) { $rec['input_keys'] = ($names -join ',') }
    }
    return $rec
}

function Write-Prompt($rec, [string]$prompt, [string]$mode) {
    $text = Protect-Text $prompt
    $rec['prompt_len'] = $prompt.Length
    $sha = [Security.Cryptography.SHA256]::Create()
    $rec['prompt_sha'] = (($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($text)) | ForEach-Object { $_.ToString('x2') }) -join '').Substring(0, 16)
    if ($text -ne $prompt) { $rec['prompt_redacted'] = $true }
    if ($mode -eq 'wazuh') { $rec['prompt'] = if ($text.Length -le 2000) { $text } else { $text.Substring(0, 2000) + '...' } }
    $keep = [ordered]@{}
    foreach ($k in @('ts', 'host', 'user', 'agent', 'session', 'cwd', 'prompt_sha')) { if ($rec.Contains($k)) { $keep[$k] = $rec[$k] } }
    $keep['prompt'] = if ($text.Length -le 100000) { $text } else { $text.Substring(0, 100000) }
    $ok = $false
    try { $ok = Add-Line $PromptLog (ConvertTo-Line @{ jt_ai_prompt = $keep }) } catch { $ok = $false }
    $rec['prompt_stored'] = [bool]$ok
}

function Invoke-Hook([string]$agent, [string]$eventName) {
    # the raw bytes as UTF-8: the agents (Node.js) write UTF-8, whatever the console code page is
    $in = [Console]::OpenStandardInput()
    $ms = New-Object IO.MemoryStream
    $in.CopyTo($ms)
    $stdin = (New-Object Text.UTF8Encoding($false)).GetString($ms.ToArray()).TrimStart([char]0xFEFF)
    if (-not $stdin) { return }
    $e = $stdin | ConvertFrom-Json
    $ev = Normalize-Event $e $agent $eventName
    if ($null -eq $ev) { return }
    $name = [string]$ev['hook_event_name']
    if ($name -eq 'PostToolUse' -and $agent -ne 'cursor' -and -not (Test-Failed $ev['tool_response'])) { return }
    if ($name -eq 'PostToolUse' -and $agent -ne 'cursor') { $ev['hook_event_name'] = 'PostToolUseFailure' }
    $mode = 'off'
    if ($name -eq 'UserPromptSubmit') {
        $mode = Get-PromptMode
        if ($mode -eq 'off' -or -not ($ev['prompt'] -is [string])) { return }
    }
    $rec = New-Record $ev $agent
    if ($name -eq 'UserPromptSubmit') { Write-Prompt $rec $ev['prompt'] $mode }
    Add-Line $Log (ConvertTo-Line @{ jt_ai = $rec }) | Out-Null
}

try {
    [Console]::InputEncoding = [Text.Encoding]::UTF8
} catch { }
if ($SyncConfig) {
    try { Sync-Config } catch { }
    exit 0
}
if ($Agents -notcontains $Agent) { $Agent = 'claude-code' }
try { Invoke-Hook $Agent $Event } catch { if ($env:JT_AI_AGENT_DEBUG) { [Console]::Error.WriteLine($_.ToString() + ' ' + $_.InvocationInfo.PositionMessage) } }
if ($JsonOut -contains $Agent) { [Console]::Out.Write("{}`n") }
exit 0
