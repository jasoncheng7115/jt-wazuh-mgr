#!/usr/bin/env python3
"""The PowerShell hook's secret patterns, generated from the Python hook's REDACT list so the two
never drift (tests/test_pack_ai_agent.py checks the block in jt-ai-agent-hook.ps1).

    tools/gen_ps1_redact.py            print the block
    tools/gen_ps1_redact.py --write    replace the block in packs/jt-ai-agent/agent/jt-ai-agent-hook.ps1
"""
import importlib.util
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PY = os.path.join(ROOT, 'packs', 'jt-ai-agent', 'agent', 'jt-ai-agent-hook.py')
PS1 = os.path.join(ROOT, 'packs', 'jt-ai-agent', 'agent', 'jt-ai-agent-hook.ps1')
BEGIN, END = '# BEGIN REDACT (generated by tools/gen_ps1_redact.py, do not edit)', '# END REDACT'


def block():
    spec = importlib.util.spec_from_file_location('jthook', PY)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    # one Add per pair: an array literal of two-element arrays unrolls its first pair in PowerShell
    lines = [BEGIN, '$Redact = New-Object System.Collections.ArrayList']
    for rx, repl in mod.REDACT:
        pat = rx.pattern
        if rx.flags & re.S:
            pat = '(?s)' + pat
        rep = re.sub(r'\\(\d)', r'$\1', repl)
        q = lambda s: "'" + s.replace("'", "''") + "'"
        lines.append('[void]$Redact.Add(@(%s, %s))' % (q(pat), q(rep)))
    lines.append(END)
    return '\n'.join(lines)


def main(argv):
    text = block()
    if '--write' not in argv:
        print(text)
        return 0
    with open(PS1, encoding='utf-8') as fh:
        body = fh.read()
    i, j = body.index(BEGIN), body.index(END) + len(END)
    with open(PS1, 'w', encoding='utf-8', newline='\r\n') as fh:
        fh.write(body[:i] + text + body[j:])
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
